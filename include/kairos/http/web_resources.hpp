// ║  kairos/http/web_resources.hpp — compiled-in web asset registry          ║
// ║                                                                          ║
// ║  The implementation (web_resources.cpp) is GENERATED at build time by    ║
// ║  cmake/GenerateWebResources.cmake from the files under web/. Every       ║
// ║  asset is emitted as a chunked raw string literal, so arbitrary text     ║
// ║  content (UTF-8 templates, CSS, JS, SVG) survives byte-for-byte.         ║
// ║                                                                          ║
// ║  Text assets only — binary files and NUL bytes are not supported.        ║
// ║                                                                          ║
// ║  Spec reference: §26.5, §26.6 (Roadmap §3.1 embedded fallback)          ║
// ╚════════════════════════════════════════════════════════════════════════════╝
#pragma once

#include <string_view>
#include <vector>

namespace kairos::http::web_resources {

/// One embedded asset. `path` is the virtual path relative to the web root,
/// e.g. "templates/base.html" or "static/css/kairos.css".
struct WebResource {
    std::string_view path;
    std::string_view content;
};

/// All embedded web assets (path → content), sorted by path.
/// Generated by cmake/GenerateWebResources.cmake; regenerated automatically
/// whenever any file under web/ changes.
const std::vector<WebResource>& embedded_resources();

}  // namespace kairos::http::web_resources
